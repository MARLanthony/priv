export interface LegalIntakePromptOptions {
  jurisdiction?: string;
  clientName?: string;
}

/** Builds the user message containing the client's description. */
export function buildLegalIntakeUserPrompt(
  problemText: string,
  options: LegalIntakePromptOptions = {},
): string {
  const context: string[] = [];
  if (options.jurisdiction) context.push(`Jurisdiction: ${options.jurisdiction}`);
  if (options.clientName) context.push(`Client name: ${options.clientName}`);

  return [
    'CLIENT DESCRIPTION:',
    '"""',
    problemText.trim(),
    '"""',
    ...(context.length > 0 ? ['', 'CONTEXT:', ...context] : []),
    '',
    'Analyse the description above and reply with the JSON object described in your instructions.',
  ].join('\n');
}
